# Asegúrate de que el archivo tenga el nombre correcto (ajústalo si es necesario)
df = pd.read_csv('datos_clasificados.csv', encoding='latin1', sep=';')
df = df[['objeto', 'clasificacion_del_contrato']].dropna()

# Codificar etiquetas
label_encoder = LabelEncoder()
df['label'] = label_encoder.fit_transform(df['clasificacion_del_contrato'])
num_labels = len(label_encoder.classes_)

# División train/val
train_texts, val_texts, train_labels, val_labels = train_test_split(
    df['objeto'].tolist(), df['label'].tolist(),
    test_size=0.1, stratify=df['label'], random_state=42
)

# Tokenizador y datasets
model_name = 'dccuchile/bert-base-spanish-wwm-cased'
tokenizer = AutoTokenizer.from_pretrained(model_name)

def tokenize(batch):
    return tokenizer(batch['text'], truncation=True, padding='max_length', max_length=128)

train_ds = Dataset.from_dict({'text': train_texts, 'label': train_labels})
val_ds = Dataset.from_dict({'text': val_texts, 'label': val_labels})
ds = DatasetDict({'train': train_ds, 'validation': val_ds})
ds = ds.map(tokenize, batched=True)
ds = ds.remove_columns(['text'])
ds.set_format('torch')

# Modelo
model = AutoModelForSequenceClassification.from_pretrained(model_name, num_labels=num_labels)

# Entrenamiento optimizado
training_args = TrainingArguments(
    output_dir='./results',
    evaluation_strategy='epoch',
    per_device_train_batch_size=16,
    per_device_eval_batch_size=16,
    num_train_epochs=2,
    fp16=True,
    weight_decay=0.01,
    logging_steps=10,
    save_total_limit=1
)
trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=ds['train'],
    eval_dataset=ds['validation'],
)

# Ejecutar entrenamiento
trainer.train()

# Guardar modelo y tokenizer en Google Drive
trainer.save_model('/content/drive/MyDrive/modelo_entrenado_beto')
tokenizer.save_pretrained('/content/drive/MyDrive/modelo_entrenado_beto')

# Evaluación
preds = trainer.predict(ds['validation'])
y_pred = np.argmax(preds.predictions, axis=1)
print(classification_report(val_labels, y_pred, target_names=label_encoder.classes_))

